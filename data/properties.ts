export const properties: Property[] = raw.map((p) => PropertySchema.parse(p));

export const featuredProperties = properties.filter((p) => p.featured);

export function getPropertyBySlug(slug: string): Property | undefined {
  return properties.find((p) => p.slug === slug);
}

export function getSimilarProperties(
  property: Property,
  limit = 3,
): Property[] {
  return properties
    .filter((p) => p.id !== property.id)
    .map((p) => ({
      p,
      score:
        (p.type === property.type ? 2 : 0) +
        (p.community === property.community ? 2 : 0) +
        (Math.abs(p.price - property.price) < property.price * 0.5 ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.p);
}
